# Variable = A container for a value (string,integer,float,boolean)
# a variable behaves as if it was the value it contains

#strings
first_name = "Hemanth S"
food  = "Biryani"
email = "Hem1234@fake.com"

print(f"Hello {first_name}")
print(f"I like {food}")
print(f"My email is {email}")

#integer
age =25
quantity = 30
no_of_people = 2000
print(f"I am {age} years of age")
print(f"There are  {quantity} people in my team")
print(f"There are {no_of_people} in my department")

 # float
price = 10.95
gpa = 8.2
distance = 8.2
print(f"the price of biryani is {price} per plate")
print(f"My gpa is {gpa}")
print(f"My house is {distance} km from my office")

#Boolean True or false
is_student = True
